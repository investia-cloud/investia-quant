# ===============================
# Histogram Plot Function
# ===============================
def plot_hist_with_stats(
    data,
    title,
    xlabel,
    color,
    filename,
    low_pct=0,
    high_pct=100,
    bins=50
):
    low, high = np.percentile(data, [low_pct, high_pct])
    filtered = data[(data >= low) & (data <= high)]

    fig = plt.figure(figsize=(10, 5))
    plt.hist(filtered, bins=bins, color=color, alpha=0.7, edgecolor="black")

    plt.axvline(np.median(data), color="black", linestyle="--", label="Median")
    plt.axvline(np.percentile(data, 5), color="gray", linestyle=":", label="5%")
    plt.axvline(np.percentile(data, 95), color="gray", linestyle=":", label="95%")

    plt.title(f"{title} ({low_pct}–{high_pct} pct range)")
    plt.xlabel(xlabel)
    plt.ylabel("Frequency")
    plt.legend()
    plt.grid(alpha=0.3)

    save_show(fig, filename)


