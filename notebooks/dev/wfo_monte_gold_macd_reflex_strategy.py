"""# **Walk Forward Optimization**"""

import pandas as pd
import numpy as np
import yfinance as yf
import vectorbt as vbt
from itertools import product

# -------------------------
# Download Data
# -------------------------
symbol = "GOLD"
start_date = "1960-01-01"
end_date = "2030-01-01"
interval = "1d"

df = yf.download(symbol, start=start_date, end=end_date,
                 interval=interval, multi_level_index=False)

df.index = pd.to_datetime(df.index)

# -------------------------
# Parameter Grid
# -------------------------

MACD_FAST = [10,12,14]
MACD_SIGNAL = [7,9,11]
MACD_SLOW = [22,26,30]

REFLEX_FAST_PERIOD = [4,5,6]
REFLEX_PERIOD = [12,14,16]
REFLEX_SHIFT = [4,5,6]
REFLEX_SLOW_PERIOD = [11,13,15]

# -------------------------
# Indicator Functions
# -------------------------

def rma(series, period):
    return series.ewm(alpha=1/period, adjust=False).mean()

def calculate_reflex(df, rsi_period, fast_period, slow_period):
    df = df.copy()
    delta = df['Close'].diff()
    delta_rma = rma(delta, rsi_period)

    df['Fast_Reflex'] = rma(delta_rma, fast_period)
    df['Slow_Reflex'] = rma(delta_rma, slow_period)
    return df

def reflex_rising(df, rsi_p, fast_p, slow_p, shift):
    df = calculate_reflex(df, rsi_p, fast_p, slow_p)
    return df['Fast_Reflex'] > df['Fast_Reflex'].shift(shift)

def calculate_macd(df, fast, slow, signal):
    df = df.copy()
    df["EMA_fast"] = df["Close"].ewm(span=fast, adjust=False).mean()
    df["EMA_slow"] = df["Close"].ewm(span=slow, adjust=False).mean()
    df["MACD"] = df["EMA_fast"] - df["EMA_slow"]
    df["Signal"] = df["MACD"].ewm(span=signal, adjust=False).mean()
    df["MACD_prev"] = df["MACD"].shift(1)
    return df

def macd_cross_below_0(df, fast, slow, signal):
    df = calculate_macd(df, fast, slow, signal)
    return (df["MACD_prev"] >= 0) & (df["MACD"] < 0)

# -------------------------
# Walk-Forward Optimization
# -------------------------

def run_walk_forward(df, train_years=4, test_years=1):

    results = []

    max_lookback = max(
        MACD_FAST + MACD_SLOW +
        REFLEX_FAST_PERIOD + REFLEX_PERIOD +
        REFLEX_SHIFT + REFLEX_SLOW_PERIOD
    )
    padding = max_lookback + 10

    start_year = df.index[0].year
    end_year = df.index[-1].year

    for train_start in range(start_year,
                             end_year - train_years - test_years + 2):

        train_end = train_start + train_years - 1
        test_start = train_end + 1
        test_end = test_start + test_years - 1

        train_start_idx = df.index.get_loc(df[df.index.year == train_start].index[0])
        train_end_idx   = df.index.get_loc(df[df.index.year == train_end].index[-1])
        test_start_idx  = df.index.get_loc(df[df.index.year == test_start].index[0])
        test_end_idx    = df.index.get_loc(df[df.index.year == test_end].index[-1])

        train_slice = df.iloc[max(0, train_start_idx - padding):train_end_idx + 1].copy()
        test_slice  = df.iloc[max(0, test_start_idx - padding):test_end_idx + 1].copy()

        train_rel_start = train_start_idx - max(0, train_start_idx - padding)
        train_rel_end   = train_end_idx   - max(0, train_start_idx - padding)
        test_rel_start  = test_start_idx  - max(0, test_start_idx - padding)
        test_rel_end    = test_end_idx    - max(0, test_start_idx - padding)

        best_perf = -np.inf
        best_params = None

        for macd_f, macd_s, macd_sig, \
            r_fast, r_period, r_shift, r_slow in product(
                MACD_FAST,
                MACD_SLOW,
                MACD_SIGNAL,
                REFLEX_FAST_PERIOD,
                REFLEX_PERIOD,
                REFLEX_SHIFT,
                REFLEX_SLOW_PERIOD
        ):

            entry_raw = reflex_rising(
                train_slice, r_period, r_fast, r_slow, r_shift
            )

            exit_raw = macd_cross_below_0(
                train_slice, macd_f, macd_s, macd_sig
            )

            entry = entry_raw.iloc[train_rel_start:train_rel_end+1]
            exit = exit_raw.iloc[train_rel_start:train_rel_end+1]

            pf_train = vbt.Portfolio.from_signals(
                close=df['Open'].iloc[train_start_idx:train_end_idx+1],
                entries=entry.shift(1).astype(bool).fillna(False).to_numpy(),
                exits=exit.shift(1).astype(bool).fillna(False).to_numpy(),
                init_cash=100_000,
                fees=0.001,
                slippage=0.002,
                freq='1d'
            )

            if pf_train.total_return() > best_perf:
                best_perf = pf_train.total_return()
                best_params = (
                    macd_f, macd_s, macd_sig,
                    r_fast, r_period, r_shift, r_slow
                )

        results.append({
            "train_period": f"{train_start}-{train_end}",
            "test_period": f"{test_start}-{test_end}",
            "params": best_params,
            "test_slice": test_slice,
            "test_rel_start": test_rel_start,
            "test_rel_end": test_rel_end
        })

    return results

# -------------------------
# Run WFO
# -------------------------

wf_results = run_walk_forward(df)

# -------------------------
# Combine Test Periods
# -------------------------

combined = pd.DataFrame()

print("=== Walk-Forward Optimized Parameters ===")

for i, res in enumerate(wf_results):

    macd_f, macd_s, macd_sig, \
    r_fast, r_period, r_shift, r_slow = res["params"]

    print(
        f"{i+1}: Train {res['train_period']} | Test {res['test_period']} | "
        f"MACD({macd_f},{macd_s},{macd_sig}) | "
        f"REFLEX(fast={r_fast}, period={r_period}, shift={r_shift}, slow={r_slow})"
    )

    test_slice = res["test_slice"]

    test_slice["entry_signal"] = reflex_rising(
        test_slice, r_period, r_fast, r_slow, r_shift
    )

    test_slice["exit_signal"] = macd_cross_below_0(
        test_slice, macd_f, macd_s, macd_sig
    )

    trimmed = test_slice.iloc[
        res["test_rel_start"]:res["test_rel_end"] + 1
    ]

    combined = pd.concat([combined, trimmed])

combined = combined.sort_index()

# -------------------------
# Final Portfolio
# -------------------------

pf = vbt.Portfolio.from_signals(
    close=combined["Open"],
    entries=combined["entry_signal"].shift(1).astype(bool).fillna(False).to_numpy(),
    exits=combined["exit_signal"].shift(1).astype(bool).fillna(False).to_numpy(),
    init_cash=100_000,
    fees=0.001,
    slippage=0.002,
    freq='1d'
)

print("\n=== Combined GOLD WFO Portfolio Stats ===")
print(pf.stats())

pf.plot().show()

