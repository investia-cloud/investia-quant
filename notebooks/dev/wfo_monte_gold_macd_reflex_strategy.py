# ===============================
# Block Bootstrap
# ===============================
def block_bootstrap_returns(returns, block_size, n_samples):
    n = len(returns)
    samples = np.zeros((n_samples, n))

    for i in range(n_samples):
        idx = 0
        while idx < n:
            start = np.random.randint(0, n - block_size)
            block = returns[start:start + block_size]
            length = min(block_size, n - idx)
            samples[i, idx:idx + length] = block[:length]
            idx += length

    return samples


bootstrapped_returns = block_bootstrap_returns(
    returns,
    block_size=BLOCK_SIZE,
    n_samples=N_SIM
)

# ===============================
# Equity Curves
# ===============================
equity_curves = INIT_CASH * np.cumprod(1 + bootstrapped_returns, axis=1)

# Total return
total_returns = equity_curves[:, -1] / INIT_CASH - 1


# ===============================
# Max Drawdown
# ===============================
def max_drawdown(equity):
    peak = np.maximum.accumulate(equity)
    dd = equity / peak - 1
    return dd.min()

max_drawdowns = np.array([max_drawdown(eq) for eq in equity_curves])


# ===============================
# Sharpe Ratio
# ===============================
def sharpe_ratio(returns, freq=252):
    mean = np.mean(returns)
    std = np.std(returns)
    if std == 0:
        return 0
    return np.sqrt(freq) * mean / std

sharpes = np.array([
    sharpe_ratio(bootstrapped_returns[i])
    for i in range(N_SIM)
])


# ===============================
